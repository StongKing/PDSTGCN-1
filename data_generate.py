def banner(text: str) -> None:
    print("\n" + "=" * 100)
    print(text)
    print("=" * 100)


def require_file(path: Path) -> None:
    if not path.exists():
        raise FileNotFoundError(f"Required input file not found: {path}")


def normalize_id_series(s: pd.Series) -> pd.Series:
    out = s.astype("string").str.strip()
    out = out.replace({"": pd.NA, "nan": pd.NA, "NaN": pd.NA, "None": pd.NA, "<NA>": pd.NA})
    out = out.str.replace(r"^(-?\d+)\.0$", r"\1", regex=True)
    return out


def haversine_m(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6371000.0
    p1 = math.radians(lat1)
    p2 = math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2.0) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2.0) ** 2
    return 2.0 * r * math.atan2(math.sqrt(a), math.sqrt(max(1.0 - a, 0.0)))


def interval_index(ts: pd.Series, t0: pd.Timestamp, freq: pd.Timedelta) -> np.ndarray:
    x = pd.to_datetime(ts, errors="coerce")
    vals = ((x - t0) / freq).to_numpy(dtype=float)
    return np.floor(vals + 1e-9).astype(np.int64)


def load_coordinates(station_ids: List[str]) -> pd.DataFrame:
    """Return one row per station_id with station_name/lat/lon where available."""
    station_set = set(station_ids)
    pieces: List[pd.DataFrame] = []

    if STATION_METADATA.exists():
        m = pd.read_csv(STATION_METADATA, low_memory=False)
        id_col = "id" if "id" in m.columns else ("station_id" if "station_id" in m.columns else None)
        if id_col is not None:
            m[id_col] = normalize_id_series(m[id_col])
            keep = [id_col]
            for c in ["station_name", "latitude", "longitude"]:
                if c in m.columns:
                    keep.append(c)
            z = m[m[id_col].isin(station_set)][keep].copy()
            z = z.rename(columns={id_col: "station_id"})
            pieces.append(z)

    # Fallback to the inventory file for missing coordinates.
    if INVENTORY_MAIN.exists():
        inv = pd.read_csv(INVENTORY_MAIN, low_memory=False)
        id_col = "id" if "id" in inv.columns else ("station_id" if "station_id" in inv.columns else None)
        if id_col is not None and {"latitude", "longitude"}.issubset(inv.columns):
            inv[id_col] = normalize_id_series(inv[id_col])
            inv["latitude"] = pd.to_numeric(inv["latitude"], errors="coerce")
            inv["longitude"] = pd.to_numeric(inv["longitude"], errors="coerce")
            inv = inv[inv[id_col].isin(station_set) & inv["latitude"].notna() & inv["longitude"].notna()].copy()
            if "timestamp" in inv.columns:
                inv["timestamp"] = pd.to_datetime(inv["timestamp"], errors="coerce")
                inv = inv.sort_values("timestamp")
            keep = [id_col, "latitude", "longitude"]
            if "station_name" in inv.columns:
                keep.append("station_name")
            inv = inv.groupby(id_col, as_index=False, sort=False).tail(1)[keep]
            inv = inv.rename(columns={id_col: "station_id"})
            pieces.append(inv)

    # Active-station file is useful for names even when coordinate files are missing.
    if V7_ACTIVE_STATIONS.exists():
        a = pd.read_csv(V7_ACTIVE_STATIONS, low_memory=False)
        if "station_id" in a.columns:
            a["station_id"] = normalize_id_series(a["station_id"])
            keep = ["station_id"] + (["station_name"] if "station_name" in a.columns else [])
            pieces.append(a[a["station_id"].isin(station_set)][keep].copy())

    out = pd.DataFrame({"station_id": station_ids})
    out["station_name"] = ""
    out["latitude"] = np.nan
    out["longitude"] = np.nan

    for p in pieces:
        p = p.drop_duplicates("station_id", keep="last").set_index("station_id")
        for c in ["station_name", "latitude", "longitude"]:
            if c not in p.columns:
                continue
            mapping = p[c]
            vals = out["station_id"].map(mapping)
            if c == "station_name":
                mask = vals.notna() & (vals.astype(str).str.len() > 0)
                out.loc[mask, c] = vals[mask].astype(str)
            else:
                vals = pd.to_numeric(vals, errors="coerce")
                mask = vals.notna()
                out.loc[mask, c] = vals[mask]

    return out


def add_edge(counter: Dict[Tuple[int, int], int], u: int, v: int, w: int) -> None:
    if w <= 0 or u == v:
        return
    counter[(int(u), int(v))] = int(counter.get((int(u), int(v)), 0)) + int(w)


def update_counter(total: Dict[Tuple[int, int], int], delta: Dict[Tuple[int, int], int], sign: int) -> None:
    for e, w in delta.items():
        new_w = int(total.get(e, 0)) + sign * int(w)
        if new_w == 0:
            total.pop(e, None)
        elif new_w < 0:
            raise RuntimeError(f"Rolling graph count became negative for edge {e}: {new_w}")
        else:
            total[e] = new_w


