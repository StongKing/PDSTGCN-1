"""
Generate the Divvy-2017 PDST-GCN dataset from the physics-consistent V7
10-minute closed-system reconstruction.

The script is intentionally downstream-only: it DOES NOT infer bike states,
operator relocations, or fleet membership again.  Those are taken from the
V6.4 -> V7 reconstruction.

Forecasting task
----------------
10-minute sampling; 6 historical states -> 6 future states (1 h -> 1 h).
The model node set is

    node 0             : mesoscopic in-transit node
    nodes 1, ..., N-1  : V7 active Divvy stations

Node feature channels are compatible with the current PDST-GCN code:
    0: bike inventory/state count
    1: time-of-day in [0,1)
    2: day-of-week in {1/7,...,1}

Dynamic graph
-------------
For every valid forecasting sample, one one-hour predefined dynamic graph is
formed from the SAME historical hour as the sample input.  It uses physically
observed V7 transitions:
    station -> 0       user departures
    0 -> station       user arrivals
    station -> station operator relocation
Weights are transition counts.  The graph is directed; the model constructs
forward/backward diffusion matrices from it.

The dynamic graphs are stored sparsely.  A dense tensor of shape roughly
(4454, 568, 568) would be several GB, so forcing the old dense adj_matrices
format is wasteful.  lib/utils.py in PDSTGCN-1 materializes only the current
mini-batch on the GPU/CPU.

Static graph
------------
Built from TRAINING-PERIOD support only (to avoid topology leakage from the
validation/test period).  It is undirected for the ASTGCN Chebyshev branch.
Observed training user-OD and relocation relations are included, and node 0 is
connected to stations that participate in mesoscopic transitions.

Typical local usage
-------------------
1. Run the supplied upstream Divvy V6.4/V7 reconstruction scripts.
2. Edit the USER SETTINGS below if your paths differ.
3. Run:
       python data_generate.py
4. Then:
       python prepareData.py --config configurations/DIVVY_astgcn.conf
       python train_ASTGCN_r.py --config configurations/DIVVY_astgcn.conf
"""

